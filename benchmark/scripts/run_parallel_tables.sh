#!/usr/bin/env bash
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$REPO_ROOT"

DEVICES="${BENCHMARK_CUDA_VISIBLE_DEVICES:-0,1,2,3}"
OUTPUT_ROOT="benchmark/results/perf-parallel-$(date -u +%Y%m%d)"
SITE="benchmark/configs/local/site-h200-readme-build.yaml"
EDGE_BUILD_DIR=""
WARMUP_RUNS="1"
MEASURED_RUNS="5"
DRY_RUN_ONLY=0
DISCOVER_CUDNN_RUNTIME=1
CUDNN_LOG_CHECK=1
CUDNN_PROFILE="${ED_PROFILE_CUDNN_SDPA:-1}"

CFG_SUITE="benchmark/configs/suites/cfg-parallel.yaml"
SP_SUITE="benchmark/configs/suites/sp-parallel.yaml"
SP_MAX_RUNS="6"

usage() {
  cat <<'EOF'
Usage: bash benchmark/scripts/run_parallel_tables.sh [options]

Options:
  --devices IDS           GPU ids available to the suite. Default: 0,1,2,3
  --output-root DIR       Output root for cfg-parallel and sp-parallel results.
  --site FILE             Local site config with model/binary paths.
  --edge-build-dir DIR    Override edge_dit_cli/sample paths with DIR/bin.
  --warmup-runs N         Warm-up runs per benchmark case. Default: 1
  --measured-runs N       Measured runs per benchmark case. Default: 5
  --dry-run               Preview and validate the expanded suites only.
  --no-cudnn-discovery    Do not prepend Python NVIDIA CUDA runtime libraries.
  --no-cudnn-log-check    Do not fail on cuDNN SDPA fallback log checks.
  -h, --help              Show this help.

This script reproduces the docs/performance.md Parallel Execution tables:
  - cfg-parallel: SD3 Medium, 1 GPU vs CFG-2
  - sp-parallel: FLUX 1024 s50 and 2048 s50, SP-1/SP-2/SP-4

The SP suite also contains diagnostic workloads. This script intentionally runs
the first 6 sp-parallel expansions and validates that they are exactly the two
FLUX workloads at 1, 2, and 4 GPUs before execution.
EOF
}

while [ "$#" -gt 0 ]; do
  case "$1" in
    --devices)
      DEVICES="${2:?--devices requires a value}"
      shift
      ;;
    --devices=*)
      DEVICES="${1#*=}"
      ;;
    --output-root)
      OUTPUT_ROOT="${2:?--output-root requires a value}"
      shift
      ;;
    --output-root=*)
      OUTPUT_ROOT="${1#*=}"
      ;;
    --site)
      SITE="${2:?--site requires a value}"
      shift
      ;;
    --site=*)
      SITE="${1#*=}"
      ;;
    --edge-build-dir)
      EDGE_BUILD_DIR="${2:?--edge-build-dir requires a value}"
      shift
      ;;
    --edge-build-dir=*)
      EDGE_BUILD_DIR="${1#*=}"
      ;;
    --warmup-runs)
      WARMUP_RUNS="${2:?--warmup-runs requires a value}"
      shift
      ;;
    --warmup-runs=*)
      WARMUP_RUNS="${1#*=}"
      ;;
    --measured-runs)
      MEASURED_RUNS="${2:?--measured-runs requires a value}"
      shift
      ;;
    --measured-runs=*)
      MEASURED_RUNS="${1#*=}"
      ;;
    --dry-run)
      DRY_RUN_ONLY=1
      ;;
    --no-cudnn-discovery)
      DISCOVER_CUDNN_RUNTIME=0
      ;;
    --no-cudnn-log-check)
      CUDNN_LOG_CHECK=0
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      echo "unknown argument: $1" >&2
      usage >&2
      exit 2
      ;;
  esac
  shift
done

make_effective_site() {
  if [ -z "$EDGE_BUILD_DIR" ]; then
    printf '%s\n' "$SITE"
    return
  fi

  mkdir -p benchmark/tmp
  local tmp_site="benchmark/tmp/parallel-site-$(date -u +%Y%m%dT%H%M%SZ)-$$.yaml"
  python3 - "$SITE" "$EDGE_BUILD_DIR" "$tmp_site" <<'PY'
from pathlib import Path
import sys

import yaml

site_path = Path(sys.argv[1]).resolve()
build_dir = Path(sys.argv[2]).resolve()
out_path = Path(sys.argv[3]).resolve()

site = yaml.safe_load(site_path.read_text(encoding="utf-8")) or {}
paths = site.setdefault("paths", {})
paths["edge_dit_cli"] = str(build_dir / "bin" / "ed-cli")
paths["edge_dit_sample"] = str(build_dir / "bin" / "ed-sample")
paths["edge_dit_cli_cudnn"] = str(build_dir / "bin" / "ed-cli")
paths["edge_dit_sample_cudnn"] = str(build_dir / "bin" / "ed-sample")

notes = site.setdefault("notes", [])
notes.append(f"Generated by run_parallel_tables.sh from {site_path}.")
notes.append(f"edge-dit.cpp binaries overridden with {build_dir}/bin.")
out_path.write_text(yaml.safe_dump(site, sort_keys=False), encoding="utf-8")
print(out_path)
PY
}

resolve_site_python() {
  python3 - "$EFFECTIVE_SITE" <<'PY'
from pathlib import Path
import os
import sys

import yaml

override = os.environ.get("PYTHON_BIN")
if override:
    print(override)
    raise SystemExit

site = yaml.safe_load(Path(sys.argv[1]).read_text(encoding="utf-8")) or {}
print((site.get("paths") or {}).get("diffusers_python") or "python3")
PY
}

discover_nvidia_runtime_paths() {
  "$1" - <<'PY'
from pathlib import Path
import importlib.util
import os

modules = [
    "nvidia.cublas",
    "nvidia.cuda_nvrtc",
    "nvidia.cuda_runtime",
    "nvidia.cudnn",
]
paths = []

def add(path: Path) -> None:
    text = str(path)
    if path.is_dir() and text not in paths:
        paths.append(text)

for module in modules:
    spec = importlib.util.find_spec(module)
    if spec is None or not spec.submodule_search_locations:
        continue
    root = Path(list(spec.submodule_search_locations)[0])
    add(root / "lib")

cudnn_root = os.environ.get("CUDNN_ROOT")
if cudnn_root:
    add(Path(cudnn_root) / "lib")
    add(Path(cudnn_root) / "lib64")

cuda_home = os.environ.get("CUDA_HOME") or os.environ.get("CUDA_PATH")
if cuda_home:
    add(Path(cuda_home) / "lib64")
    add(Path(cuda_home) / "lib")

print(":".join(paths))
PY
}

dry_run_suite() {
  local suite="$1"
  local max_runs="$2"
  local dry_run_json="$3"
  local args=()
  if [ -n "$max_runs" ]; then
    args+=(--max-runs "$max_runs")
  fi
  BENCHMARK_CUDA_VISIBLE_DEVICES="$DEVICES" \
    python3 benchmark/orchestration/run_suite.py \
      --suite "$suite" \
      --site "$EFFECTIVE_SITE" \
      --dry-run \
      --systems edge-dit.cpp \
      --warmup-runs "$WARMUP_RUNS" \
      --measured-runs "$MEASURED_RUNS" \
      "${args[@]}" > "$dry_run_json"
}

summarize_dry_run() {
  local label="$1"
  local dry_run_json="$2"
  python3 - "$label" "$dry_run_json" <<'PY'
import json
import sys

label = sys.argv[1]
with open(sys.argv[2], "r", encoding="utf-8") as f:
    data = json.load(f)
runs = data.get("runs", [])
items = [
    f"{run['workload']}:gpu{run['gpu_count']}:{run.get('parallel_mode')}"
    for run in runs
]
print(f"{label}: {len(runs)} runs")
for item in items:
    print(f"  - {item}")
PY
}

validate_cfg_dry_run() {
  python3 - "$1" <<'PY'
import json
import sys

with open(sys.argv[1], "r", encoding="utf-8") as f:
    data = json.load(f)
got = [(run["workload"], run["gpu_count"], run.get("parallel_mode")) for run in data.get("runs", [])]
expected = [
    ("sd3-medium-t2i-1024-s50", 1, "cfg"),
    ("sd3-medium-t2i-1024-s50", 2, "cfg"),
]
if got != expected:
    print("cfg-parallel expansion mismatch", file=sys.stderr)
    print(f"expected: {expected}", file=sys.stderr)
    print(f"got:      {got}", file=sys.stderr)
    raise SystemExit(2)
PY
}

validate_sp_dry_run() {
  python3 - "$1" <<'PY'
import json
import sys

with open(sys.argv[1], "r", encoding="utf-8") as f:
    data = json.load(f)
got = [(run["workload"], run["gpu_count"], run.get("parallel_mode")) for run in data.get("runs", [])]
expected = [
    ("flux1-dev-t2i-1024-s50", 1, "sequence"),
    ("flux1-dev-t2i-1024-s50", 2, "sequence"),
    ("flux1-dev-t2i-1024-s50", 4, "sequence"),
    ("flux1-dev-t2i-2048-s50", 1, "sequence"),
    ("flux1-dev-t2i-2048-s50", 2, "sequence"),
    ("flux1-dev-t2i-2048-s50", 4, "sequence"),
]
if got != expected:
    print("sp-parallel FLUX expansion mismatch", file=sys.stderr)
    print(f"expected: {expected}", file=sys.stderr)
    print(f"got:      {got}", file=sys.stderr)
    raise SystemExit(2)
PY
}

run_suite() {
  local suite="$1"
  local max_runs="$2"
  local args=()
  if [ -n "$max_runs" ]; then
    args+=(--max-runs "$max_runs")
  fi
  BENCHMARK_CUDA_VISIBLE_DEVICES="$DEVICES" \
  LD_LIBRARY_PATH="$RUNTIME_LD_LIBRARY_PATH" \
  ED_PROFILE_CUDNN_SDPA="$CUDNN_PROFILE" \
    python3 benchmark/orchestration/run_suite.py \
      --suite "$suite" \
      --site "$EFFECTIVE_SITE" \
      --execute \
      --resume \
      --systems edge-dit.cpp \
      --warmup-runs "$WARMUP_RUNS" \
      --measured-runs "$MEASURED_RUNS" \
      --output-root "$OUTPUT_ROOT" \
      "${args[@]}"
}

verify_cudnn_logs() {
  if [ "$CUDNN_LOG_CHECK" -eq 0 ]; then
    return
  fi

  local fallback_pattern="Could not load library libnvrtc|ED_CUDNN_SDPA build failed|No execution plans support the graph"
  if find "$OUTPUT_ROOT" -name stderr.log -print0 | xargs -0 -r rg -n "$fallback_pattern"; then
    echo "cuDNN SDPA fallback or runtime-load failure detected in benchmark stderr logs." >&2
    exit 1
  fi

  if [ "$CUDNN_PROFILE" != "0" ]; then
    if ! find "$OUTPUT_ROOT" -name stderr.log -print0 | xargs -0 -r rg -q "ED_CUDNN_SDPA (success|async build .*result=success)"; then
      echo "ED_PROFILE_CUDNN_SDPA is enabled, but no successful ED_CUDNN_SDPA log entry was found." >&2
      exit 1
    fi
  fi
}

EFFECTIVE_SITE="$(make_effective_site)"
CFG_DRY_RUN_JSON="$(mktemp)"
SP_DRY_RUN_JSON="$(mktemp)"
trap 'rm -f "$CFG_DRY_RUN_JSON" "$SP_DRY_RUN_JSON"' EXIT

dry_run_suite "$CFG_SUITE" "" "$CFG_DRY_RUN_JSON"
dry_run_suite "$SP_SUITE" "$SP_MAX_RUNS" "$SP_DRY_RUN_JSON"
validate_cfg_dry_run "$CFG_DRY_RUN_JSON"
validate_sp_dry_run "$SP_DRY_RUN_JSON"

summarize_dry_run "cfg-parallel" "$CFG_DRY_RUN_JSON"
summarize_dry_run "sp-parallel FLUX subset" "$SP_DRY_RUN_JSON"

if [ "$DRY_RUN_ONLY" -eq 1 ]; then
  cat <<EOF
Dry run only.

Effective site: $EFFECTIVE_SITE
Output root:    $OUTPUT_ROOT
EOF
  exit 0
fi

RUNTIME_LD_LIBRARY_PATH="${LD_LIBRARY_PATH:-}"
if [ "$DISCOVER_CUDNN_RUNTIME" -eq 1 ]; then
  PYTHON_FOR_RUNTIME="$(resolve_site_python)"
  NVIDIA_RUNTIME_PATHS="$(discover_nvidia_runtime_paths "$PYTHON_FOR_RUNTIME")"
  if [ -z "$NVIDIA_RUNTIME_PATHS" ]; then
    echo "could not discover Python NVIDIA CUDA runtime libraries with $PYTHON_FOR_RUNTIME" >&2
    echo "use --no-cudnn-discovery only if the required cuDNN runtime libs are already on LD_LIBRARY_PATH" >&2
    exit 2
  fi
  RUNTIME_LD_LIBRARY_PATH="${NVIDIA_RUNTIME_PATHS}${RUNTIME_LD_LIBRARY_PATH:+:${RUNTIME_LD_LIBRARY_PATH}}"
  echo "Using Python NVIDIA CUDA runtime libraries from: $NVIDIA_RUNTIME_PATHS"
fi

echo "Effective site: $EFFECTIVE_SITE"
echo "Output root:    $OUTPUT_ROOT"
echo "Devices:        $DEVICES"

run_suite "$CFG_SUITE" ""
run_suite "$SP_SUITE" "$SP_MAX_RUNS"
verify_cudnn_logs

SUMMARY="$OUTPUT_ROOT/summary.json"
TABLES="$OUTPUT_ROOT/tables.md"
python3 benchmark/analysis/aggregate.py \
  --results-dir "$OUTPUT_ROOT" \
  --include-workload sd3-medium-t2i-1024-s50 \
  --include-workload flux1-dev-t2i-1024-s50 \
  --include-workload flux1-dev-t2i-2048-s50 \
  --suite-id parallel-execution \
  --output "$SUMMARY"

python3 benchmark/analysis/generate_tables.py \
  "$SUMMARY" \
  --output "$TABLES"

cat <<EOF
Parallel execution table run complete.

Result root: $OUTPUT_ROOT
CFG runs:    $OUTPUT_ROOT/cfg-parallel
SP runs:     $OUTPUT_ROOT/sp-parallel
Summary:     $SUMMARY
Tables:      $TABLES
EOF
